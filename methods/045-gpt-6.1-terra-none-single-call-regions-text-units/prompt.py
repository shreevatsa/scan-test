#!/usr/bin/env python3
"""Generate method 045's single-call prompt and response schema from a book's type list.

Part 1 (regions) is method 042's region prompt, generated by region_prompt.py (a byte copy of method 042's prompt.py):
the book's region types with their class rules, the larger units, the nesting rule and method 042's continuation,
reading-order and uncertainty rules, without its rule against transcription. Parts 2 and 3 (transcription and units)
are method 044's rules, with the book's unit types, furniture, flows and relations generated by transcription_prompt.py
(a byte copy of method 044's prompt.py). The model does not know the line finder's lines, so each region has one
entry per printed line, with no fixed count.

Usage: uv run --offline python methods/045-…/prompt.py schema/types/kale-1913.json [--schema]
"""
import argparse
import json
from pathlib import Path

import region_prompt as rp
import transcription_prompt as tp

HERE = Path(__file__).resolve().parent


def build_prompt(tl):
    template = (HERE / "prompt-template.txt").read_text()
    book = tl["title"].rstrip(".") + ". " + tl.get("description", "").strip()
    conventions = tl.get("conventions") or ["Transcribe as printed, in Unicode NFC."]
    return (template.replace("<<BOOK>>", book.strip())
            .replace("<<TYPES>>", rp.type_lines(tl))
            .replace("<<LARGER_UNITS>>\n", rp.larger_units(tl))
            .replace("<<NESTING>>\n", rp.nesting_rule(tl))
            .replace("<<CONVENTIONS>>", "\n".join("  - " + c for c in conventions))
            .replace("<<UNIT_TYPES>>", tp.type_lines(tl))
            .replace("<<FURNITURE>>", ", ".join(tp.furniture(tl)) or "none in this book")
            .replace("<<FLOWS>>", "\n".join(f"  - {k}: {v}" for k, v in tl["flows"].items()))
            .replace("<<RELATIONS>>\n", tp.relation_lines(tl)))


def build_schema(tl):
    region = {"type": "object", "additionalProperties": False,
              "required": ["type", "box_1000", "keep", "reading_order", "uncertain", "continues_from_earlier",
                           "continues_later", "lines", "note"],
              "properties": {
                  "type": {"type": "string", "enum": rp.type_enum(tl)},
                  "box_1000": {"type": "array", "items": {"type": "integer", "minimum": 0, "maximum": 1000}, "minItems": 4, "maxItems": 4},
                  "keep": {"type": "boolean"},
                  "reading_order": {"type": ["integer", "null"], "minimum": 1},
                  "uncertain": {"type": "boolean"},
                  "continues_from_earlier": {"type": "boolean"},
                  "continues_later": {"type": "boolean"},
                  "lines": {"type": "array", "items": {
                      "type": "object", "additionalProperties": False, "required": ["text", "end"],
                      "properties": {"text": {"type": "string"}, "end": {"enum": tp.ENDS}}}},
                  "note": {"type": ["string", "null"]}}}
    base = tp.build_schema(tl, [])
    props = {"regions": {"type": "array", "items": region}}
    props.update({k: v for k, v in base["properties"].items() if k != "regions"})
    return {"type": "object", "additionalProperties": False, "required": list(props), "properties": props}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("types", type=Path)
    parser.add_argument("--schema", action="store_true")
    args = parser.parse_args()
    tl = json.loads(args.types.read_text())
    print(json.dumps(build_schema(tl), indent=1, ensure_ascii=False) if args.schema else build_prompt(tl), end="")


if __name__ == "__main__":
    main()
